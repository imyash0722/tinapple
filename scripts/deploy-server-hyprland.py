#!/usr/bin/env python3
import os
import sys
import subprocess
import shutil

HYPRLAND_LUA = """-- Tinapple Hyprland Server Configuration with Headless Remote Screen (wayvnc)
hl.config({ autogenerated = false })

------------------
---- MONITORS ----
------------------
-- Headless virtual screen for remote desktop and ii-tools screen mirroring
hl.monitor({
    output   = "HEADLESS-1",
    mode     = "1920x1080@60",
    position = "0x0",
    scale    = "1",
})

-- Physical displays (e.g. laptop internal LVDS-1 if open)
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})

-------------------
---- AUTOSTART ----
-------------------
hl.on("hyprland.start", function ()
    hl.exec_cmd("hyprctl output create headless HEADLESS-1")
    hl.exec_cmd("wayvnc --render-cursor 0.0.0.0 5900")
    hl.exec_cmd("/usr/lib/xdg-desktop-portal-hyprland &")
    hl.exec_cmd("/usr/lib/xdg-desktop-portal &")
end)

-------------------------------
---- ENVIRONMENT VARIABLES ----
-------------------------------
hl.env("XCURSOR_SIZE", "24")
hl.env("HYPRCURSOR_SIZE", "24")
hl.env("XDG_CURRENT_DESKTOP", "Hyprland")
hl.env("XDG_SESSION_TYPE", "wayland")
hl.env("XDG_SESSION_DESKTOP", "Hyprland")

-----------------------
----- PERMISSIONS -----
-----------------------
hl.permission("/usr/(lib|libexec|lib64)/xdg-desktop-portal-hyprland", "screencopy", "allow")
hl.permission("/usr/(bin|local/bin)/wayvnc", "screencopy", "allow")

-----------------------
---- LOOK AND FEEL ----
-----------------------
hl.config({
    general = {
        gaps_in  = 6,
        gaps_out = 12,
        border_size = 2,
        col = {
            active_border   = { colors = {"rgba(38bdf8ee)", "rgba(7ec789ee)"}, angle = 45 },
            inactive_border = "rgba(3f4755aa)",
        },
        resize_on_border = false,
        allow_tearing = false,
        layout = "dwindle",
    },
    decoration = {
        rounding       = 14,
        rounding_power = 2,
        active_opacity   = 1.0,
        inactive_opacity = 0.95,
        shadow = {
            enabled = true,
            range   = 8,
            color   = 0x66000000,
        },
        blur = {
            enabled = true,
            size    = 6,
            passes  = 2,
        },
    },
    misc = {
        disable_hyprland_logo = true,
        disable_splash_rendering = true,
    },
    input = {
        kb_layout = "us",
        follow_mouse = 1,
        touchpad = {
            natural_scroll = true,
        },
    },
})

---------------------
---- KEYBINDINGS ----
---------------------
local mainMod = "SUPER"
local terminal = "kitty"

hl.bind(mainMod .. " + Q", hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + C", hl.dsp.window.close())
hl.bind(mainMod .. " + V", hl.dsp.window.float({ action = "toggle" }))

hl.bind(mainMod .. " + left",  hl.dsp.focus({ direction = "left" }))
hl.bind(mainMod .. " + right", hl.dsp.focus({ direction = "right" }))
hl.bind(mainMod .. " + up",    hl.dsp.focus({ direction = "up" }))
hl.bind(mainMod .. " + down",  hl.dsp.focus({ direction = "down" }))

for i = 1, 10 do
    local key = i % 10
    hl.bind(mainMod .. " + " .. key, hl.dsp.focus({ workspace = i }))
    hl.bind(mainMod .. " + SHIFT + " .. key, hl.dsp.window.move({ workspace = i }))
end
"""

XDPH_CONF = """screencopy {
    max_fps = 60
    allow_token_by_default = true
}
"""

PORTALS_CONF = """[preferred]
default = hyprland;gtk
org.freedesktop.impl.portal.ScreenCast = hyprland
org.freedesktop.impl.portal.Screenshot = hyprland
"""

SYSTEMD_SERVICE = """[Unit]
Description=Tinapple Hyprland Compositor & Remote Desktop (wayvnc)
Documentation=https://github.com/imyash0722/tinapple
After=network.target systemd-user-sessions.service user@1000.service
Wants=pipewire.service wireplumber.service

[Service]
Type=simple
User=pineapple
Group=users
SupplementaryGroups=wheel audio input storage video autologin media
WorkingDirectory=/home/pineapple
Environment=XDG_CURRENT_DESKTOP=Hyprland
Environment=XDG_SESSION_TYPE=wayland
Environment=XDG_SESSION_DESKTOP=Hyprland
Environment=XDG_RUNTIME_DIR=/run/user/1000
Environment=WLR_LIBINPUT_NO_DEVICES=1
Environment=AQ_NO_MODIFIERS=1
ExecStart=/usr/bin/Hyprland
Restart=always
RestartSec=3

[Install]
WantedBy=multi-user.target
"""

def run(cmd):
    print(f"+ {cmd}")
    res = subprocess.run(cmd, shell=True, text=True, capture_output=True)
    if res.stdout:
        print(res.stdout.strip())
    if res.stderr:
        print(f"stderr: {res.stderr.strip()}")
    if res.returncode != 0:
        print(f"Exit code: {res.returncode}")
    return res

def main():
    print("=== 1. Writing Hyprland Lua Configuration ===")
    hypr_dir = "/home/pineapple/.config/hypr"
    os.makedirs(hypr_dir, exist_ok=True)
    with open(f"{hypr_dir}/hyprland.lua", "w") as f:
        f.write(HYPRLAND_LUA)
    with open(f"{hypr_dir}/xdph.conf", "w") as f:
        f.write(XDPH_CONF)

    portal_dir = "/home/pineapple/.config/xdg-desktop-portal"
    os.makedirs(portal_dir, exist_ok=True)
    with open(f"{portal_dir}/hyprland-portals.conf", "w") as f:
        f.write(PORTALS_CONF)

    run("chown -R pineapple:users /home/pineapple/.config/hypr /home/pineapple/.config/xdg-desktop-portal")

    print("=== 2. Updating Manifest YAML ===")
    manifest_path = "/etc/tinapple/manifest.yaml"
    if os.path.exists(manifest_path):
        with open(manifest_path, "r") as f:
            content = f.read()
        if "- niri" in content:
            content = content.replace("- niri", "- hyprland")
            print("Replaced niri with hyprland in manifest profiles")
        if "services:" in content and "hyprland:" not in content:
            content = content.replace(
                "services:\n",
                "services:\n    hyprland:\n        enabled: true\n        user: pineapple\n        port: 5900\n"
            )
            print("Added hyprland service definition to manifest")
        with open(manifest_path, "w") as f:
            f.write(content)

    print("=== 3. Writing Systemd Service ===")
    service_path = "/etc/systemd/system/tinapple-hyprland.service"
    with open(service_path, "w") as f:
        f.write(SYSTEMD_SERVICE)

    print("=== 4. Reloading and Starting tinapple-hyprland.service ===")
    run("systemctl daemon-reload")
    run("systemctl enable --now tinapple-hyprland.service")

    print("=== 5. Verification ===")
    run("sleep 2")
    run("systemctl is-active tinapple-hyprland.service")
    run("pgrep -a Hyprland || true")
    run("pgrep -a wayvnc || true")
    run("ss -tulpn | grep 5900 || true")

if __name__ == "__main__":
    main()
